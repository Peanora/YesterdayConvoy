"""Generate the runtime's typed v0.7 tables from the approved source snapshot.

Run from the repository root with Python 3. No Unity or external packages needed.
The original design JSON remains the source of truth; this does not retune values.
"""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'docs/design/parameters.v0.7.json'
TARGET = ROOT / 'Assets/Scripts/Runtime/FormationCampaignRules.cs'
data = json.loads(SOURCE.read_text(encoding='utf-8'))

def cs(value):
    return json.dumps(str(value), ensure_ascii=False)

def num(value):
    return format(float(value), '.9g') + 'f'

def strings(values):
    return 'new string[]{' + ','.join(cs(x) for x in values) + '}'

def ints(values):
    return 'new int[]{' + ','.join(str(x) for x in values) + '}'

def stats(values):
    return 'new Dictionary<string,float>{' + ','.join('{' + cs(k) + ',' + num(v) + '}' for k, v in values.items()) + '}'

def card_id(unit_id):
    return {'SLUG':'CARD_ORIGINIUM_SLUG','TAL':'CARD_TALULAH_TRIAL','WIS':'CARD_WISADEL_APRIL'}.get(unit_id, 'CARD_' + unit_id)

lines = ['// Generated by tools/generate_formation_rules.py from the user-approved v0.7 snapshot.',
         '// Edit the authoritative design first, then regenerate. Legacy campaign tables are independent.',
         'using System;', 'using System.Collections.Generic;', 'using System.Linq;',
         'namespace YesterdayConvoy', '{', '    public static class FormationCampaignRules', '    {',
         '        public const string Version = "0.7.0";',
         '        public sealed class UnitDefinition', '        {',
         '            public string Id, CardId, Name, DamageType, Size, Role, Recovery, Effect;',
         '            public int Cost;',
         '            public float Health, Attack, Armor, MagicResistance, Interval, Range, MoveSpeed, InitialSP, RequiredSP, ActionSeconds;',
         '            public string[] Factions, Styles;',
         '        }',
         '        public sealed class DataRecord', '        {',
         '            public string Id, Name, Kind, Tier, Effect, Extra, Recipe;',
         '            public int[] Planes = Array.Empty<int>(), Levels = Array.Empty<int>();',
         '            public Dictionary<string,float> Stats = new Dictionary<string,float>();',
         '        }',
         '        public sealed class NodeDefinition', '        {',
         '            public string Id, Kind; public int Plane, BaseGold, XP, DefenderCount;',
         '            public float HealthScale, AttackScale, TimeLimit;',
         '        }',
         '        public sealed class DefenderDefinition', '        {',
         '            public string Name, DamageType, Effect;',
         '            public float Health, Attack, Armor, MagicResistance, Interval, Range, InitialSP, RequiredSP, ActionSeconds;',
         '        }',
         '        public sealed class BossDefinition', '        {',
         '            public string NodeId, Name, Effect;',
         '            public float Health, Attack, Armor, MagicResistance, Interval, Range, InitialSP, RequiredSP, ActionSeconds;',
         '        }',
         '        public static readonly UnitDefinition[] AllUnits = {']
for u in data['units']:
    fields = {'Id':cs(u['id']), 'CardId':cs(card_id(u['id'])), 'Name':cs(u['name']), 'Cost':str(u['cost']),
              'DamageType':cs(u['damage_type']), 'Size':cs(u['size']), 'Role':cs(u['role']),
              'Factions':strings(u['factions']), 'Styles':strings(u['styles'])}
    for target, source in [('Health','hp'),('Attack','attack'),('Armor','armor'),('MagicResistance','mr'),('Interval','interval'),('Range','range'),('MoveSpeed','speed')]:
        fields[target] = num(u[source])
    skill = u['skill']
    for target, source in [('InitialSP','initial'),('RequiredSP','required'),('ActionSeconds','action')]:
        fields[target] = num(skill[source])
    fields['Recovery'], fields['Effect'] = cs(skill['recovery']), cs(skill['effect'])
    lines.append('            new UnitDefinition{' + ','.join(k + '=' + v for k,v in fields.items()) + '},')
lines.append('        };')

for target, source in [('AllPreplans','preplans'),('AllAugments','augments'),('AllItems','items'),('AllComponents','components'),('AllFactions','factions'),('AllStyles','styles')]:
    lines.append('        public static readonly DataRecord[] ' + target + ' = {')
    for record in data[source]:
        key = record.get('id', record.get('recipe', ''))
        fields = {'Id':cs(key),'Name':cs(record['name']),'Effect':cs(record.get('effect',record.get('text',''))),
                  'Extra':cs(record.get('extra',record.get('decision',''))),'Kind':cs(record.get('kind','')),
                  'Tier':cs(record.get('tier','')),'Recipe':cs(record.get('recipe','')),
                  'Planes':ints(record.get('planes',[])), 'Levels':ints(record.get('levels',[])), 'Stats':stats(record.get('stats',{}))}
        lines.append('            new DataRecord{' + ','.join(k + '=' + v for k,v in fields.items()) + '},')
    lines.append('        };')

curve = {r['id']:r for r in data['enemy_curve']}
lines.append('        public static readonly NodeDefinition[] Nodes = {')
for n in data['nodes']:
    c = curve.get(n['id'], {})
    # The timing column is in the approved Word/Markdown table rather than nodes JSON.
    limit = 'float.PositiveInfinity' if n['kind']=='奖励' else '150f' if n['id']=='3-7' else '120f' if n['kind']=='首领' else '90f'
    lines.append('            new NodeDefinition{Id='+cs(n['id'])+',Kind='+cs(n['kind'])+',Plane='+str(n['plane'])+',BaseGold='+str(n.get('base_gold',0))+',XP='+str(n.get('xp',0))+',DefenderCount='+str(c.get('count',0))+',HealthScale='+num(c.get('hp_mult',1))+',AttackScale='+num(c.get('attack_mult',1))+',TimeLimit='+limit+'},')
lines.append('        };')
lines.append('        public static readonly DefenderDefinition[] Defenders = {')
for row in data['defenders']:
    sp=re.search(r'(\d+)/(\d+)SP',row[8])
    action=re.search(r'动作([\d.]+)秒',row[8])
    lines.append('            new DefenderDefinition{Name='+cs(row[0])+',Health='+num(row[1])+',Attack='+num(row[2])+',Armor='+num(row[3])+',MagicResistance='+num(row[4])+',Interval='+num(row[5])+',Range='+num(row[6])+',DamageType='+cs(row[7])+',Effect='+cs(row[8])+',InitialSP='+num(sp[1])+',RequiredSP='+num(sp[2])+',ActionSeconds='+num(action[1])+'},')
lines.append('        };')
lines.append('        public static readonly BossDefinition[] Bosses = {')
for row in data['bosses']:
    sp=re.search(r'(\d+)/(\d+)SP',row[8])
    lines.append('            new BossDefinition{NodeId='+cs(row[0])+',Name='+cs(row[1])+',Health='+num(row[2])+',Attack='+num(row[3])+',Armor='+num(row[4])+',MagicResistance='+num(row[5])+',Interval='+num(row[6])+',Range='+num(row[7])+',Effect='+cs(row[8])+',InitialSP='+num(sp[1])+',RequiredSP='+num(sp[2])+',ActionSeconds='+num(3 if row[0]=='3-7' else 1)+'},')
lines += ['        };',
          '        public static readonly int[] ExperienceToNext = {0,2,4,6,10,20,36,56,80,100,0};',
          '        public static readonly int[][] ShopOdds = {']
for level in range(1,11):
    lines.append('            ' + ints(data['shop_odds'][str(level)] if isinstance(data['shop_odds'],dict) else data['shop_odds'][level-1]) + ',')
lines += ['        };',
          '        public static UnitDefinition Find(string id) => AllUnits.FirstOrDefault(u => u.Id == id || u.CardId == id || u.CardId == "CARD_" + id || u.Name == id);',
          '        public static DataRecord FindRecord(string id) => AllPreplans.Concat(AllAugments).Concat(AllItems).Concat(AllComponents).Concat(AllFactions).Concat(AllStyles).FirstOrDefault(r => r.Id == id || r.Name == id);',
          '    }', '}']
TARGET.write_text('\n'.join(lines)+'\n',encoding='utf-8')
print('Generated',TARGET,':',len(data['units']),'units;',len(data['nodes']),'nodes;',len(data['preplans']),'preplans')
